/** applies_to: offered for places, recipes, or both ('all'). */
export type Category = {
  id: number;
  slug: string;
  name: string;
  icon: string;
  color: string;
  sort?: number;
  published?: boolean;
  applies_to?: 'all' | 'places' | 'recipes';
};
export type ImageUrls = { sm: string; lg: string };
export type Photo = {
  id: string;
  width: number;
  height: number;
  alt: string;
  position: number;
  in_gallery: boolean;
  user_id: number | null;
  author: string | null;
  created_at: number;
  urls: ImageUrls;
};
export type Review = { id: number; rating: number; comment: string; created_at: number; updated_at: number; user_id: number; author: string };
export type Place = {
  id: number;
  slug: string;
  name: string;
  lat: number;
  lng: number;
  address: string;
  city: string;
  price_level: number | null;
  tags: string[];
  description: string;
  website: string;
  phone: string;
  instagram: string;
  hours: string;
  icon: string | null;
  marker_icon: string;
  tried: boolean;
  published: boolean;
  category: Category | null;
  rating: number | null;
  review_count: number;
  cover: ImageUrls | null;
  author_id: number | null;
  author: string | null;
  created_at: number;
  updated_at: number;
};
export type PlaceDetail = Place & {
  reviews: Review[];
  photos: Photo[];
  recipes: { id: number; slug: string; title: string; cover_image_id: string | null }[];
};
export type RecipeCard = {
  id: number;
  slug: string;
  title: string;
  description: string;
  tags: string[];
  category: Category | null;
  cover: (ImageUrls & { id: string }) | null;
  published: boolean;
  author_id: number | null;
  author: string | null;
  created_at: number;
  updated_at: number;
};
export type Ingredient = { qty: string; name: string };
export type Recipe = RecipeCard & {
  ingredients: Ingredient[];
  body: string;
  place: { id: number; slug: string; name: string } | null;
  photos: Photo[];
  products: Product[];
};
export type RecipeList = { items: RecipeCard[]; total: number; limit: number; offset: number };
export type User = { id: number; email: string; pseudo: string; role: 'admin' | 'editor' };
export type Meal = 'breakfast' | 'lunch' | 'dinner';
export type PlanningDay = { date: string; meals: Record<Meal, RecipeCard[]> };
export type PlanningWeek = { week: string; prev: string; next: string; today: string; days: PlanningDay[] };
export type Settings = {
  map_private: boolean;
  recipes_private: boolean;
  planning_private: boolean;
  products_private: boolean;
  cellar_private: boolean;
  products_enabled: boolean;
  cellar_enabled: boolean;
  grapeminds_enabled: boolean;
  ollama_enabled: boolean;
};
export type Section = 'map' | 'recipes' | 'planning' | 'products' | 'cellar';
export type ProductKind = 'pantry' | 'wine';
export type WineType = 'red' | 'white' | 'rose' | 'sparkling' | 'sweet' | 'spirit' | 'beer' | 'other';
/** `quantity`, `purchase_price_cents` and `location` are only sent to members. */
export type Product = {
  id: number;
  slug: string;
  kind: ProductKind;
  name: string;
  brand: string;
  description: string;
  tags: string[];
  category: Category | null;
  cover: (ImageUrls & { id: string }) | null;
  quantity?: number;
  store: string;
  price_cents: number | null;
  barcode: string | null;
  wine_type: WineType | null;
  vintage: number | null;
  appellation: string;
  region: string;
  country: string;
  grape: string;
  abv: number | null;
  drink_from: number | null;
  drink_until: number | null;
  purchase_price_cents?: number | null;
  location?: string;
  grapeminds_id: string | null;
  author_id: number | null;
  author: string | null;
  created_at: number;
  updated_at: number;
};
export type ProductDetail = Product & { photos: Photo[]; recipes: { id: number; slug: string; title: string }[] };
export type ProductList = { items: Product[]; total: number; limit: number; offset: number };
